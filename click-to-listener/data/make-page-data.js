// Bundles order.json and flow.json (both real captures) into ../click-data.js for the page.
//   node make-page-data.js
const fs = require("fs");
const order = JSON.parse(fs.readFileSync(__dirname + "/order.json")), flow = JSON.parse(fs.readFileSync(__dirname + "/flow.json"));
fs.writeFileSync(__dirname + "/../click-data.js", "/* generated by data/make-page-data.js from order.json and flow.json; do not edit */\nwindow.CLICK_DATA = " + JSON.stringify({ order, flow }) + ";\n");
console.log("wrote click-data.js");
