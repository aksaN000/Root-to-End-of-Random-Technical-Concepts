// Bundles capture.json into ../capture-data.js for the page, keeping only what the page shows:
// the command outputs, the dev server banner, what the browser received for main.tsx and App.tsx,
// and the utilities part of the stylesheet Tailwind generated for the navbar.
//   node make-page-data.js
const fs = require("fs"), path = require("path");
const C = JSON.parse(fs.readFileSync(path.join(__dirname, "capture.json"), "utf8"));
const css = C.served.css.body, at = css.indexOf("@layer utilities {");
let depth = 0, end = at;
for (let i = css.indexOf("{", at); i < css.length; i++) { if (css[i] === "{") depth++; else if (css[i] === "}") { depth--; if (!depth) { end = i + 1; break; } } }
// drop daisyUI's own layers (its component classes) so the page shows Tailwind's utilities; count what was dropped
function stripLayers(text) {
  let out = "", i = 0, dropped = 0;
  while (i < text.length) {
    const j = text.indexOf("  @layer daisyui", i);
    if (j < 0) { out += text.slice(i); break; }
    out += text.slice(i, j); let d = 0, k = text.indexOf("{", j);
    for (; k < text.length; k++) { if (text[k] === "{") d++; else if (text[k] === "}") { d--; if (!d) break; } }
    dropped++; i = k + 2;
  }
  return { out, dropped };
}
const util = stripLayers(css.slice(at, end));
const page = {
  captured: C.captured, versions: C.versions, browser: C.browser,
  steps: C.steps.map(s => ({ label: s.label, cmd: s.cmd, cwd: s.cwd, status: s.status, out: s.out })),
  devBanner: C.devBanner,
  served: { index: C.served.index.body, main: C.served.main.body, app: C.served.app.body.split("\nimport * as RefreshRuntime")[0] },
  cssHeader: css.split("\n")[0], cssBytes: C.served.css.bytes, utilities: util.out, daisyLayersDropped: util.dropped
};
fs.writeFileSync(path.join(__dirname, "..", "capture-data.js"), "/* Real output captured by data/capture.js on " + C.captured + " (" + C.versions.node + ", npm " + C.versions.npm + "). Generated by data/make-page-data.js. */\nwindow.WDV_CAPTURE = " + JSON.stringify(page) + ";\n");
console.log("wrote capture-data.js (" + JSON.stringify(page).length + " bytes)");
