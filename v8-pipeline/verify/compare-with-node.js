// Compares the page's V8 model (../v8-model.js) with real V8 bytecode from this Node binary.
// Usage: node verify/compare-with-node.js [count] [seed]
const M = require("../v8-model.js");
const { execFileSync } = require("child_process");
const fs = require("fs"), os = require("os"), path = require("path");
const count = +process.argv[2] || 200;
let seed = +process.argv[3] || 7;
const rnd = n => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed % n; };
const ops = ["+", "-", "*", "/", "%", "|", "&", "^", "<<"];
function ex(d) {
  if (d <= 0 || rnd(3) === 0) { const k = rnd(5); return k === 0 ? String(rnd(5)) : k === 1 ? String(rnd(300)) : "abc"[rnd(3)]; }
  const s = ex(d - 1) + " " + ops[rnd(ops.length)] + " " + ex(d - 1);
  return rnd(3) === 0 ? "(" + s + ")" : s;
}
const exprs = Array.from({ length: count }, () => ex(4));
const file = path.join(os.tmpdir(), "root-to-end-v8-cases.js");
fs.writeFileSync(file, exprs.map((e, i) => `function g${i}(a,b,c){return ${e};}\ng${i}(1,2,3);`).join("\n"));
const out = execFileSync(process.execPath, ["--print-bytecode", file], { maxBuffer: 1 << 28 }).toString();
const real = {};
out.split("[generated bytecode for function: ").forEach(b => {
  const m = b.match(/^(g\d+) /);
  if (m) real[m[1]] = b.split("\n").filter(l => /@\s+\d+ :/.test(l)).map(l => l.replace(/^.*: ([0-9a-f]{2} )+\s*/, "").replace(/\s+\(0x.*$/, "").trim());
});
let pass = 0; const failures = [];
exprs.forEach((e, i) => {
  const mine = M.text(M.gen(M.parse(e).ast)), r = real["g" + i] || [];
  if (JSON.stringify(mine) === JSON.stringify(r)) pass++;
  else { failures.push({ input: "function g(a,b,c){return " + e + ";}", v8: r, model: mine }); console.log("DIFF", e, "\n  V8:   ", r.join(" | "), "\n  model:", mine.join(" | ")); }
});
const seed0 = +process.argv[3] || 7;
require("../../tools/report.js")("v8-bytecode", { passed: pass === count, cases: count, matched: pass, seeds: [{ count: count, seed: seed0 }], reference: "V8 " + process.versions.v8 + " (Node " + process.versions.node + ")", failures: failures });
console.log(`${pass}/${count} expressions match V8 ${process.versions.v8} byte for byte`);
process.exitCode = pass === count ? 0 : 1;
